"""Run the actual DW completer with authentic local Git sources and byte verification."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

DAY = Path(__file__).resolve().parent
loc = json.loads((DAY / 'adopter-stage2-isolated.json').read_text())['adopters']['driftwood']
source, estate = Path(loc['dir']), Path(loc['estate'])
root = Path(tempfile.mkdtemp(prefix='pavf-dw-real-completer-', dir='/private/tmp'))
repo = root / 'driftwood'
subprocess.run(['git', 'clone', '--quiet', '--no-hardlinks', str(source), str(repo)], check=True)
for child in source.iterdir():
    if child.name == '.git':
        continue
    dest = repo / child.name
    if child.is_dir():
        shutil.copytree(child, dest, dirs_exist_ok=True)
    else:
        shutil.copy2(child, dest)
old_path = repo / 'twin/forward-intel/v1/feed.json'
current_path = repo / 'twin/forward-intel/v2/feed.json'
old_hash = hashlib.sha256(old_path.read_bytes()).hexdigest()
expected = hashlib.sha256(current_path.read_bytes()).hexdigest()
current_path.write_bytes(b'stale current-major fixture before actual completer\n')
# A local publication clone's own main may intentionally lag its authenticated
# origin/main. Reproduce the cached genuine upstream main in a disposable mirror.
hub_source = DAY.parents[3] / '.estate-publish/hub'
hub_mirror = root / 'hub-upstream.git'
subprocess.run(['git', 'clone', '--quiet', '--mirror', str(hub_source), str(hub_mirror)], check=True)
upstream_main = subprocess.check_output(['git', '-C', str(hub_source), 'rev-parse', 'origin/main'], text=True).strip()
subprocess.run(['git', '-C', str(hub_mirror), 'update-ref', 'refs/heads/main', upstream_main], check=True)
urls = {'https://github.com/policy-as-versioned-platform/platform': estate / 'platform-tools',
        **{f'https://github.com/policy-as-versioned-{name}/{name}': estate / name for name in ('nist','ico','feeds','insurer')},
        'https://github.com/policy-as-versioned-flux/policy-as-versioned-flux': hub_mirror}
env = dict(os.environ, GITSIGN_REKOR_MODE='offline', GIT_CONFIG_COUNT=str(len(urls)),
           PATH=str(Path(sys.executable).parent) + os.pathsep + os.environ['PATH'])
for index, (url, local) in enumerate(urls.items()):
    assert local.is_dir(), local
    env[f'GIT_CONFIG_KEY_{index}'] = f'url.{local}.insteadOf'
    env[f'GIT_CONFIG_VALUE_{index}'] = url
argv = ['bash', '.github/scripts/complete-feed-bump.sh']
done = subprocess.run(argv, cwd=repo, env=env, text=True, capture_output=True, timeout=300)
log = DAY / 'driftwood-source-A-real-completer.log'
log.write_text(done.stdout + done.stderr)
result = {'argv': argv, 'cwd': str(repo), 'local_sources': {url: str(path) for url, path in urls.items()},
          'exit': done.returncode, 'log': str(log), 'hub_genuine_origin_main': upstream_main, 'hub_source': str(hub_source), 'old_v1_before_sha256': old_hash,
          'old_v1_after_sha256': hashlib.sha256(old_path.read_bytes()).hexdigest(),
          'expected_v2_sha256': expected, 'actual_v2_sha256': hashlib.sha256(current_path.read_bytes()).hexdigest()}
(DAY / 'driftwood-source-A-real-completer.json').write_text(json.dumps(result, indent=2) + '\n')
assert done.returncode == 0, (done.stdout + done.stderr)[-3500:]
assert result['old_v1_after_sha256'] == old_hash
assert result['actual_v2_sha256'] == expected
# All signed parents remain the actual isolated estate. Only the temporary
# adopter's committed output was regenerated by the actual completer.
verify = [sys.executable, str(repo / '.github/scripts/platform-tools.py'), '--adopter-dir', str(repo),
          '--tools-dir', str(estate / 'platform-tools'), 'verify', str(repo), '--estate-clone', str(estate)]
checked = subprocess.run(verify, cwd=repo, env=env, text=True, capture_output=True, timeout=180)
vlog = DAY / 'driftwood-source-A-real-completer-verify.log'
vlog.write_text(checked.stdout + checked.stderr)
result['verify'] = {'argv': verify, 'exit': checked.returncode, 'log': str(vlog)}
(DAY / 'driftwood-source-A-real-completer.json').write_text(json.dumps(result, indent=2) + '\n')
assert checked.returncode == 0, (checked.stdout + checked.stderr)[-3500:]
print('actual completer + genuine tools5 byte verify PASS; current v2 restored, historical v1 unchanged', flush=True)
