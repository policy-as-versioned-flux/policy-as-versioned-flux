def git(cwd: Path, *args: str, dated: str | None = None) -> str:
    """Run git in the fixture's fixed environment.

    `dated` overrides the fixed commit date for one call. Every fixture commit otherwise carries
    the same instant, which is what makes the tree reproducible — and is also why a fixture that
    needs two states *separated in time* has to say so explicitly (build ticket 35).
    """
    env = dict(_GIT_ENV)
    if dated:
        env.update({"GIT_AUTHOR_DATE": dated, "GIT_COMMITTER_DATE": dated})
    proc = subprocess.run(
        ["git", *_CONFIG, *args],
        cwd=str(cwd),
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {proc.stderr.decode('utf-8', 'replace').strip()}")
    return proc.stdout.decode("utf-8")


def _write(root: Path, files: dict[str, str]) -> None:
    for rel, content in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def build(dest: str | Path) -> Path:
    """Create the fixture repository at `dest` and return its path.

    Two commits on purpose: the world layer lands first so the overlays can pin the world
    commit they resolve against, which is what makes them separately versioned units.
    """
    root = Path(dest)
    root.mkdir(parents=True, exist_ok=True)
    git(root, "init", "-q", "-b", "main", "--object-format=sha1")

    _write(root, WORLD_FILES)
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "world layer")
    world_commit = git(root, "rev-parse", "HEAD").strip()

    _write(root, OVERLAY_FILES)
    _write(root, BEHAVIOURAL_FILES)
    for org in ("netflix", "intel"):
        _write(
            root,
            {
                f"orgs/{org}/meta.yaml": (
                    f"id: {org}\nunit: overlay\norg: {org}\nworld_ref: {world_commit}\n"
                )
            },
        )
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "org overlays")
    return root


